-- 3. margen_fijo NULL <- remarque (activos con remarque cargado). Regla 12 de nova-domus-maestra §13.
--    Los ids afectados quedan en 08_margen_fijo_copiado_ids.txt (rollback).
with u as (
  update inventario set margen_fijo = remarque, updated_at = now()
  where estado = 'activo' and margen_fijo is null and remarque is not null
  returning id
) select count(*) as margen_fijo_copiados, string_agg(id::text, ',' order by id) as ids from u;

-- 4. Segunda pasada sku_mo (54): murales y racks que recibieron grupo RACK en el paso 2 o ya lo tenían.
--    Nombre empieza con MURAL/RACK, tiene medida en U y no es accesorio. Ids en 09_sku_mo_racks_ids.txt.
with u as (
  update inventario set sku_mo = 'MO-INF-RACK', updated_at = now()
  where estado='activo' and sku_mo is null and grupo='RACK' and nombre ~* '^(MURAL|RACK)' and nombre ~* '\d+ ?U'
    and nombre !~* '(bandeja|organizador|canal|tuerca|patch|kit|soporte|estante|ventilador|bander|zocalo|zócalo|rueda|accesorio|pdu)'
  returning id
) select count(*) as racks_actualizados from u;

